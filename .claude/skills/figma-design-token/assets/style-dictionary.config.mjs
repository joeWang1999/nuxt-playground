// Figma Variables (DTCG) → CSS 變數（+ Tailwind / SCSS）
// 用法：npm run tokens
// 產出檔案皆為自動產生，請勿手動修改；調整 token 請改 tokens/tokens.json 後重新執行。

// ─── 專案設定（依專案調整這一區即可） ─────────────────────────────

// Figma 匯出的 token 檔
const SOURCE = ['tokens/tokens.json']

// 產出的 CSS / SCSS 放置位置
//   Nuxt 4：'app/assets/css/'   Nuxt 3：'assets/css/'   Vue 3 + Vite：'src/assets/styles/'
const STYLE_OUT = 'src/assets/styles/'

// Tailwind 輸出：'v3'（tailwind.config 用的 JSON）、'v4'（@theme CSS）、false（不用 Tailwind）
const TAILWIND = false
// Tailwind v3 對應表輸出位置（tailwind.config 會 import 這個檔案）
const TAILWIND_V3_OUT = 'tokens/'

// 是否輸出 SCSS 變數檔 _tokens.scss（$color-text-primary: var(--color-text-primary)）
const SCSS = false

// 要從 token 路徑去掉的 Figma collection / mode 前綴，最長者優先比對。
// 例：Primitive.Primitive.color.grey.800 → color-grey-800
//     Semantic.color.text.primary        → color-text-primary
const PREFIXES = [['Primitive', 'Primitive'], ['Semantic']]

// Semantic 顏色 token 的路徑開頭；其下一層就是分類（text / background / border ...）
const SEMANTIC_COLOR_ROOT = ['Semantic', 'color']

// Semantic 分類 → Tailwind utility 的對應。
// groups 的值是 class 前綴：'' 代表不加前綴（text.primary → text-primary），
// 'icon' 代表加上分類名（icon.primary → text-icon-primary）。
// Figma 新增分類時，在這裡加上對應即可，不需要改 tailwind 設定。
const UTILITIES = {
  textColor: { v4: 'text-color', groups: { text: '', icon: 'icon', tag: 'tag' } },
  backgroundColor: {
    v4: 'background-color',
    groups: { background: 'background', surface: 'surface', tag: 'tag' },
  },
  borderColor: { v4: 'border-color', groups: { border: '' } },
  fill: { v4: 'fill', groups: { icon: 'icon' } },
  stroke: { v4: 'stroke', groups: { icon: 'icon' } },
}

// ─── 以下通常不需要修改 ─────────────────────────────────────────

const startsWith = (path, prefix) => prefix.every((key, i) => path[i] === key)

const stripPrefix = (path) => {
  const prefix = PREFIXES.filter((p) => startsWith(path, p)).sort((a, b) => b.length - a.length)[0]
  return prefix ? path.slice(prefix.length) : path
}

// 把 Semantic 顏色 token 展開成各 utility 的項目：
// { utility: 'textColor', key: 'icon-primary', cssVar: 'var(--color-icon-primary)' }
const semanticEntries = (dictionary) => {
  const entries = []
  const unmapped = new Set()
  for (const token of dictionary.allTokens) {
    if (!startsWith(token.path, SEMANTIC_COLOR_ROOT)) continue
    const [group, ...rest] = token.path.slice(SEMANTIC_COLOR_ROOT.length)
    let mapped = false
    for (const [utility, { groups }] of Object.entries(UTILITIES)) {
      if (!(group in groups)) continue
      mapped = true
      const key = [groups[group], ...rest].filter(Boolean).join('-')
      entries.push({ utility, key, cssVar: `var(--${token.name})` })
    }
    if (!mapped) unmapped.add(group)
  }
  if (unmapped.size) {
    console.warn(`⚠ 這些 Semantic 分類沒有對應到 Tailwind utility，請在 UTILITIES 加上：${[...unmapped].join(', ')}`)
  }
  return entries
}

const header = '/**\n * Do not edit directly, this file was auto-generated by `npm run tokens`.\n */\n\n'

const platforms = {
  css: {
    transforms: ['name/figma-kebab', 'color/css'],
    buildPath: STYLE_OUT,
    files: [{ destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true } }],
  },
}

if (TAILWIND === 'v3') {
  platforms.tailwind = {
    transforms: ['name/figma-kebab'],
    buildPath: TAILWIND_V3_OUT,
    files: [{ destination: 'tailwind.tokens.json', format: 'tailwind/v3' }],
  }
}

if (TAILWIND === 'v4') {
  platforms.tailwind = {
    transforms: ['name/figma-kebab'],
    buildPath: STYLE_OUT,
    files: [{ destination: 'tailwind-theme.css', format: 'tailwind/v4' }],
  }
}

if (SCSS) {
  platforms.scss = {
    transforms: ['name/figma-kebab'],
    buildPath: STYLE_OUT,
    files: [{ destination: '_tokens.scss', format: 'scss/css-var-refs' }],
  }
}

export default {
  source: SOURCE,
  hooks: {
    transforms: {
      'name/figma-kebab': {
        type: 'name',
        transform: (token) => stripPrefix(token.path).join('-'),
      },
    },
    formats: {
      // { textColor: { primary: 'var(--color-text-primary)', 'icon-primary': ... }, backgroundColor: ... }
      // 直接當作 tailwind.config 的 theme.extend 使用
      'tailwind/v3': ({ dictionary }) => {
        const result = {}
        for (const { utility, key, cssVar } of semanticEntries(dictionary)) {
          ;(result[utility] ??= {})[key] = cssVar
        }
        return JSON.stringify(result, null, 2) + '\n'
      },
      // @theme inline { --text-color-primary: var(--color-text-primary); ... }
      // 使用 utility 專屬 namespace，避免 --color-* 讓每個顏色都長出 bg-/text-/border- 全套 class
      'tailwind/v4': ({ dictionary }) => {
        const lines = semanticEntries(dictionary).map(
          ({ utility, key, cssVar }) => `  --${UTILITIES[utility].v4}-${key}: ${cssVar};`,
        )
        return `${header}@theme inline {\n${lines.join('\n')}\n}\n`
      },
      // $color-text-primary: var(--color-text-primary);
      // 值指向 CSS 變數，讓執行期換主題（例如 dark mode）時 SCSS 寫的樣式也會跟著變
      'scss/css-var-refs': ({ dictionary }) => {
        const lines = dictionary.allTokens.map((token) => `$${token.name}: var(--${token.name});`)
        return `// Do not edit directly, this file was auto-generated by \`npm run tokens\`.\n\n${lines.join('\n')}\n`
      },
    },
  },
  platforms,
}
